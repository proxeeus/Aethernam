/* 0131:0004  returns a + (b - a) * t / n (16-bit imul/idiv) */
int16_t intro_0131_0004(int16_t a, int16_t b, int16_t t, int16_t n)
{
    int32_t prod = (int32_t)(int16_t)(b - a) * t;
    return (int16_t)((int16_t)(prod / n) + a);
}

/* 0131:0022  dissolve: copies the back buffer DSPTR(0x148) to the screen DSPTR(0x14c) in
 * 7 passes of every 7th byte (pass k copies bytes k, k+7, ...), 3 retraces per pass */
void intro_0131_0022(void)
{
    uint8_t *dst = DSPTR(0x14c);                /* es = [0x14e], offsets from 0 */
    uint8_t *src = DSPTR(0x148);                /* ds = [0x14a] */
    uint16_t start = 0, off, n;
    int pass;
    for (pass = 7; pass; pass--) {
        intro_066d_00e8();
        intro_066d_00e8();
        intro_066d_00e8();
        off = start++;
        for (n = 0x23b6; n; n--) {
            dst[off] = src[off];
            off += 7;
        }
    }
}

