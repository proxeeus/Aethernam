/* 0131:01bd  _AffLineRed: copies row ysrc of the picture DSPTR(0xbf2) to row ydst (+xbegin)
 * of the draw buffer, shrunk horizontally by 2*red pixels (red clamped to 0..160) and
 * centred (the 161 unrolled variants of the original are the table above) */
